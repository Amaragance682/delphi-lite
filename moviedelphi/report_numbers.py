r"""Write report/numbers.tex: every number quoted in the report, read from the logged results.

    python -m moviedelphi.report_numbers

Each value becomes a LaTeX macro (\newcommand{\NumX}{...}) so the report never contains a number
typed by hand.
"""

import argparse
import json
import os

import pandas as pd
import torch


def fmt_int(x):
    return f"{int(x):,}".replace(",", "{,}")


def fmt(x, d=3):
    return f"{x:.{d}f}"


def pct(x, d=0):
    return f"{100 * x:.{d}f}\\%"


class Macros:

    def __init__(self):
        self.lines = []
        self.plain = {}

    def add(self, name, value):
        assert name.isalpha() and name not in self.plain, name
        self.lines.append(f"\\newcommand{{\\Num{name}}}{{{value}}}")
        self.plain[name] = value.replace("{,}", ",").replace("\\%", "%").replace("$", "").replace("\\pm", "±")

    def write(self, path, json_path):
        with open(path, "w") as f:
            f.write("% generated by python -m moviedelphi.report_numbers -- do not edit\n")
            f.write("\n".join(self.lines) + "\n")
        with open(json_path, "w") as f:
            json.dump(self.plain, f, indent=1)


def letters(s):
    """Macro-safe name: digits spelled out (LaTeX macro names are letters only)."""
    words = dict(zip("0123456789", ["Zero", "One", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight", "Nine"]))
    return "".join(words.get(c, c) for c in s if c.isalnum())


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--processed", default="data/processed")
    ap.add_argument("--results", default="results")
    ap.add_argument("--path", default="results/tables/validation_path.json")
    ap.add_argument("--out", default="report/numbers.tex")
    ap.add_argument("--main", default="DELPHI")
    ap.add_argument("--seeds", nargs="*", default=["DELPHI", "DELPHI_s2", "DELPHI_s3"])
    args = ap.parse_args()
    m = Macros()
    t = lambda name: os.path.join(args.results, "tables", name)  # noqa: E731

    with open(os.path.join(args.processed, "summary.json")) as f:
        s = json.load(f)
    raw, sp, meta = s["raw"], s["splits"], s["metadata"]
    m.add("Ratings", fmt_int(raw["ratings"]))
    m.add("Users", fmt_int(raw["users"]))
    m.add("MoviesRated", fmt_int(raw["movies_rated"]))
    for name in ("train", "val", "test"):
        m.add(f"Users{name.capitalize()}", fmt_int(sp[name]["users"]))
        m.add(f"Eligible{name.capitalize()}", fmt_int(sp[name]["eligible_users"]))
    m.add("EligibleShare", pct(sp["train"]["eligible_share"]))
    m.add("SingleDayShare", pct(1 - sp["train"]["eligible_share"]))
    m.add("FirstDayShare", pct(sp["train"]["share_events_on_first_day"]))
    m.add("Vocab", fmt_int(s["vocab"]["movies"]))
    m.add("VocabMinCount", fmt_int(s["vocab"]["min_train_count"]))
    m.add("VocabCoverage", pct(sp["train"]["in_vocab_share"], 1))
    m.add("NoYear", fmt_int(meta["movies_without_year"]))
    m.add("NoGenre", fmt_int(meta["movies_without_genres"]))
    m.add("DupTitles", fmt_int(meta["duplicate_titles"]))
    m.add("BeforeRelease", fmt_int(meta["ratings_before_release_year"]))
    busiest_day, busiest_count = next(iter(s["busiest_days"].items()))
    m.add("BusiestDay", busiest_day)
    m.add("BusiestDayCount", fmt_int(busiest_count))
    for name in ("val", "test"):
        e = sp[name]["eval_cases"]
        cap = name.capitalize()
        m.add(f"Cases{cap}", fmt_int(e["n"]))
        m.add(f"MedianHist{cap}", fmt_int(e["n_hist"]["0.5"]))
        m.add(f"MedianTarget{cap}", fmt_int(e["n_target"]["0.5"]))
        m.add(f"MedianGap{cap}", fmt_int(e["gap_days"]["0.5"]))
        m.add(f"GapOne{cap}", pct(e["share_gap_1_day"]))
        m.add(f"SecondDay{cap}", pct(e["share_target_is_second_active_day"]))

    with open(t("baseline_choice.json")) as f:
        choice = json.load(f)
    m.add("Window", str(choice["window"]))
    base_val = pd.read_csv(t("baselines_val.csv"))
    m.add("BaselineVariants", str(int((base_val.window != "static").sum())))  # candidates for RECENT-POP

    # validation path: one change per step
    if os.path.exists(args.path):
        with open(args.path) as f:
            path = json.load(f)
        for row in path:
            key = letters(row["key"])
            m.add(f"Val{key}", fmt(row["recall@20"]))
            m.add(f"Val{key}CI", fmt(row["ci"]))
            m.add(f"Val{key}Diff", f"{row['diff']:+.3f}")
            m.add(f"Val{key}DiffCI", fmt(row["diff_ci"]))
        pop = next(r for r in path if r["method"] == "POP")
        m.add("ValPopDiffAbs", fmt(abs(pop["diff"])))
    # learned weight of the popularity offset (runs that were not kept)
    for run, key in (("m7_popularity_offset", "BetaShort"), ("m8_offset_30k", "BetaLong")):
        ckpt = os.path.join("runs", run, "ckpt.pt")
        if os.path.exists(ckpt):
            m.add(key, f"{float(torch.load(ckpt, map_location='cpu', weights_only=False)['model']['pop_beta']):.2f}")

    # test results
    if os.path.exists(t("test_main.csv")):
        test = pd.read_csv(t("test_main.csv")).set_index("method")
        for method, key in (("POP", "Pop"), ("RECENT-POP", "Recent"), ("ITEM-KNN", "Knn"), (args.main, "Delphi")):
            r = test.loc[method]
            for metric, mk in (("recall@10", "RTen"), ("recall@20", "RTwenty"), ("recall@50", "RFifty"),
                               ("ndcg@20", "NTwenty"), ("hit@20", "HTwenty")):
                m.add(f"Test{key}{mk}", fmt(r[metric]))
            m.add(f"Test{key}CI", fmt(r["recall@20_ci95"]))
            for ref, rk in (("RECENT-POP", "Recent"), ("POP", "Pop")):
                if f"diff_vs_{ref}" in r and pd.notna(r[f"diff_vs_{ref}"]):
                    m.add(f"Test{key}Vs{rk}", f"{r[f'diff_vs_{ref}']:+.3f}")
                    m.add(f"Test{key}Vs{rk}CI", fmt(r[f"diff_vs_{ref}_ci95"]))
        seeds = [test.loc[x, "recall@20"] for x in args.seeds if x in test.index]
        lows = [test.loc[x, "diff_vs_RECENT-POP"] - test.loc[x, "diff_vs_RECENT-POP_ci95"]
                for x in args.seeds if x in test.index]
        if lows:
            m.add("SeedDiffMinLow", f"{min(lows):+.3f}")  # lowest 95% lower bound of a seed's gain over RECENT-POP
        if len(seeds) > 1:
            m.add("SeedMean", fmt(pd.Series(seeds).mean()))
            m.add("SeedSD", fmt(pd.Series(seeds).std(ddof=1)))
            m.add("SeedMin", fmt(min(seeds)))
            m.add("SeedMax", fmt(max(seeds)))
            m.add("SeedN", str(len(seeds)))
        rel = test.loc[args.main, "recall@20"] / test.loc["RECENT-POP", "recall@20"] - 1
        m.add("TestRelGain", pct(rel))
        rel_pop = test.loc[args.main, "recall@20"] / test.loc["POP", "recall@20"] - 1
        m.add("TestRelGainPop", pct(rel_pop))
        for name in [x for x in test.index if x.startswith("DATA")]:
            m.add(f"Test{letters(name.title())}", fmt(test.loc[name, "recall@20"]))
            m.add(f"Test{letters(name.title())}CI", fmt(test.loc[name, "recall@20_ci95"]))

    if os.path.exists(t("test_history_length.csv")):
        h = pd.read_csv(t("test_history_length.csv"))
        for method, key in ((args.main, "Delphi"), ("ITEM-KNN", "Knn")):
            for k, row in h[h.method == method].set_index("k").iterrows():
                m.add(f"Hist{key}K{letters(str(k))}", fmt(row["recall@20"]))
    if os.path.exists(t("test_controls.csv")):
        c = pd.read_csv(t("test_controls.csv")).set_index("control")
        for control, key in (("shuffle_order", "Shuffle"), ("other_user", "Other")):
            m.add(f"Ctrl{key}", fmt(c.loc[control, "recall@20"]))
            m.add(f"Ctrl{key}Diff", f"{c.loc[control, 'diff_vs_real']:+.3f}")
            m.add(f"Ctrl{key}DiffCI", fmt(c.loc[control, "diff_vs_real_ci95"]))
    if os.path.exists(t("test_buckets.csv")):
        b = pd.read_csv(t("test_buckets.csv"))
        shares = {"BothZero", "DelphiZero", "DelphiBetter", "RecentBetter"}
        for row in b.itertuples():
            # pop*: share of target movies found; *Share: shares of cases or targets; *Age: years
            is_share = row.key in shares or row.key.startswith("pop") or row.key.endswith("Share")
            value = pct(row.value) if is_share else f"{row.value:.1f}" if row.key.endswith("Age") else fmt(row.value)
            m.add(f"Bucket{letters(row.key)}", value)
    if os.path.exists(t("test_causal.csv")):  # candidates restricted to movies rated before the prediction day
        c = pd.read_csv(t("test_causal.csv")).set_index("method")
        m.add("CausalDelphi", fmt(c.loc[args.main, "recall@20"]))
        m.add("CausalRecent", fmt(c.loc["RECENT-POP", "recall@20"]))
        m.add("CausalDelphiVsRecent", f"{c.loc[args.main, 'diff_vs_RECENT-POP']:+.3f}")
        m.add("CausalDelphiVsRecentCI", fmt(c.loc[args.main, "diff_vs_RECENT-POP_ci95"]))
        lows = [c.loc[x, "diff_vs_RECENT-POP"] - c.loc[x, "diff_vs_RECENT-POP_ci95"] for x in args.seeds if x in c.index]
        m.add("CausalSeedMinLow", f"{min(lows):+.3f}")
        m.add("CausalLongGapDelphi", fmt(c.loc[args.main, "recall@20 gap 31-365 days"]))
        m.add("CausalLongGapRecent", fmt(c.loc["RECENT-POP", "recall@20 gap 31-365 days"]))
        sh = pd.read_csv(t("test_causal_shares.csv")).iloc[0]
        m.add("FutureShareTargets", pct(sh.future_share_of_targets))
        m.add("FutureShareTopTwenty", pct(sh.future_share_of_top20))
        m.add("FutureShareHits", pct(sh.future_share_of_hits))
    if os.path.exists(t("test_buckets_long.csv")):
        long = pd.read_csv(t("test_buckets_long.csv"))
        late = long[(long.method == args.main) & (long.feature == "year") & (long.bucket == "2015-19")].iloc[0]
        total = long[(long.method == args.main) & (long.feature == "year")].n.sum()
        m.add("YearLateCases", fmt_int(late.n))
        m.add("YearLateShare", pct(late.n / total))
    if os.path.exists(t("efficiency.csv")):
        e = pd.read_csv(t("efficiency.csv")).set_index("model")
        r = e.loc[args.main]
        m.add("Params", f"{r.params / 1e6:.1f}")
        m.add("TrainMinutes", f"{r.train_minutes:.0f}")
        m.add("CpuLatency", f"{r.cpu_latency_ms_median:.0f}")
        m.add("CpuThroughput", fmt_int(round(r.cpu_throughput_cases_per_s)))
        if "cuda_throughput_cases_per_s" in r:
            m.add("GpuThroughput", fmt_int(round(r.cuda_throughput_cases_per_s)))
        m.add("CpuThreads", str(int(r.cpu_threads)))

    with open("tests/test_pipeline.py") as f:
        m.add("Tests", str(sum(line.startswith("def test_") for line in f)))
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    m.write(args.out, os.path.join(args.results, "tables", "numbers.json"))
    print(f"wrote {len(m.lines)} macros to {args.out} and results/tables/numbers.json")


if __name__ == "__main__":
    main()
