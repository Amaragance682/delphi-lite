"""The validation path from the baselines to the final model, as JSON (figures) and LaTeX (report).

    python -m moviedelphi.path_table

Reads results/tables/val_main_path.csv, written by
    python -m moviedelphi.evaluate --split val --tag _path --model M1=... --model M2=... ...
"""

import json
import os

import pandas as pd

# (method in val_main_path.csv, macro key, label, what changed, short label for the figure, colour, kept?)
PATH = [
    ("POP", "Pop", "POP", "all-time popularity", "all-time popularity", "POP", True),
    ("RECENT-POP", "Recent", "RECENT-POP", "popularity in the last {W} days", "popularity, last {W} days", "RECENT-POP", True),
    ("ITEM-KNN", "Knn", "ITEM-KNN", "co-occurrence with the history, no time", "co-occurrence, no time",
     "ITEM-KNN", True),
    ("M1", "MOne", "M1 Delphi", "4 layers $\\times$ 128, age in years, 10k it.", "4 layers x 128, 10k it.",
     "#86b6ef", True),
    ("M2", "MTwo", "M2", "M1, age encoding in days", "M1, age in days", "#c3c2b7", False),
    ("M3", "MThree", "M3", "M1, every position predicts its next day", "M1, every-position loss", "#c3c2b7", False),
    ("M4", "MFour", "M4", "M1, day transitions weighted equally", "M1, transitions weighted",
     "#c3c2b7", False),
    ("M5", "MFive", "M5 final", "M1, trained for 30k iterations", "M1, 30k iterations", "#2a78d6", True),
    ("M6", "MSix", "M6", "M1, 6 layers $\\times$ 256 (3.5$\\times$ parameters)", "M1, 6 layers x 256",
     "#c3c2b7", False),
    ("M7", "MSeven", "M7", "M1 + popularity offset $\\beta\\log(1+c_{30})$", "M1 + popularity offset",
     "#c3c2b7", False),
    ("M8", "MEight", "M8", "M5 + popularity offset", "M5 + popularity offset", "#c3c2b7", False),
]


def main(csv="results/tables/val_main_path.csv", out_json="results/tables/validation_path.json",
         out_tex="report/path_table.tex", kept=None):
    df = pd.read_csv(csv).set_index("method")
    with open(os.path.join(os.path.dirname(csv), "baseline_choice.json")) as f:
        window = json.load(f)["window"]
    kept = kept or {}
    rows = []
    for method, key, label, change, short, color, keep in PATH:
        if method not in df.index:
            continue
        r = df.loc[method]
        change, short = change.replace("{W}", str(window)), short.replace("{W}", str(window))
        rows.append({"method": method, "key": key, "label": label, "change": change, "short": short, "color": color,
                     "recall@20": float(r["recall@20"]), "ci": float(r["recall@20_ci95"]),
                     "diff": float(r["diff_vs_RECENT-POP"]) if method != "RECENT-POP" else 0.0,
                     "diff_ci": float(r["diff_vs_RECENT-POP_ci95"]) if method != "RECENT-POP" else 0.0,
                     "kept": kept.get(method, keep)})
    with open(out_json, "w") as f:
        json.dump(rows, f, indent=2)

    lines = [r"\begin{tabular}{@{}llrr@{}}", r"\toprule",
             r"Step & Change (one at a time) & R@20 & $\Delta$ vs RECENT-POP \\", r"\midrule"]
    for r in rows:
        diff = "--" if r["method"] == "RECENT-POP" else f"${r['diff']:+.3f}\\pm{r['diff_ci']:.3f}$"
        name = r["label"] if r["kept"] else f"\\textcolor{{gray}}{{{r['label']}}}"
        lines.append(f"{name} & {r['change']} & {r['recall@20']:.3f} & {diff} \\\\")
        if r["method"] == "ITEM-KNN":
            lines.append(r"\midrule")
    lines += [r"\bottomrule", r"\end{tabular}"]
    os.makedirs(os.path.dirname(out_tex), exist_ok=True)
    with open(out_tex, "w") as f:
        f.write("% generated by python -m moviedelphi.path_table -- do not edit\n" + "\n".join(lines) + "\n")
    print(pd.DataFrame(rows)[["method", "recall@20", "ci", "diff", "diff_ci"]].round(4).to_string(index=False))


if __name__ == "__main__":
    main()
